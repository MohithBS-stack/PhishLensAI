"""Typed Schemas for Phase 4: Normalized Evidence, Manipulation Tactics & Unified Threat Analysis."""
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class NormalizedEvidence(BaseModel):
    """Normalized forensic evidence item across all modalities."""
    evidence_id: str = Field(description="Unique deterministic or generated identifier for this evidence item")
    source_modality: str = Field(description="Originating modality: 'text', 'url', 'screenshot', or 'audio'")
    indicator_type: str = Field(description="Indicator category (e.g. 'urgency_deadline', 'phishing_url', 'credential_harvesting')")
    description: str = Field(description="Human-readable explanation of the finding")
    supporting_excerpt: Optional[str] = Field(default=None, description="Exact raw excerpt, token, or extracted feature value")
    severity: str = Field(description="Signal severity: 'low', 'medium', 'high', or 'critical'")
    evidence_source: str = Field(description="Component producing evidence (e.g. 'sms_classifier', 'url_classifier', 'manipulation_rule')")
    confidence: Optional[float] = Field(default=None, description="Model or heuristic confidence (0.0 to 1.0) where applicable")
    observed_versus_inferred: str = Field(description="'observed' for direct input artifacts vs 'inferred' for model/heuristic outputs")
    limitations_and_missing_checks: List[str] = Field(
        default_factory=list,
        description="Explicit boundaries and omitted verifications for this evidence item"
    )


class ManipulationTactic(BaseModel):
    """Evidence-backed manipulation or social engineering tactic detected in communication."""
    tactic_id: str = Field(description="Unique identifier for the tactic")
    category: str = Field(
        description="Tactic category: 'urgency', 'authority_impersonation', 'secrecy', 'credential_request', 'payment_request', or 'identity_inconsistency'"
    )
    name: str = Field(description="Readable tactic name")
    description: str = Field(description="Detailed explanation of the psychological manipulation technique")
    severity: str = Field(description="'low', 'medium', 'high', or 'critical'")
    supporting_evidence: str = Field(description="Exact triggering excerpt or text snippet from the analyzed content")
    disclaimer: str = Field(
        default="This indicator reflects social engineering cues and is not definitive proof of malicious intent on its own.",
        description="Contextual disclaimer"
    )


class StructuredExplanation(BaseModel):
    """Structured, evidence-grounded threat explanation."""
    summary: str = Field(description="Concise high-level threat verdict summary")
    executive_brief: str = Field(description="Structured briefing strictly grounded in observed evidence")
    key_concerns: List[str] = Field(default_factory=list, description="Primary technical or social engineering concerns identified")
    manipulation_tactics_explained: List[str] = Field(
        default_factory=list,
        description="Detailed contextual breakdown of observed psychological tactics"
    )
    remediation_advice: List[str] = Field(default_factory=list, description="Safe next steps and defensive actions for the analyst/user")
    is_llm_generated: bool = Field(default=False, description="True if generated via LLM; False if generated by deterministic grounded fallback")
    model_name: Optional[str] = Field(default=None, description="Model provider or fallback engine name utilized")


class UncertaintyReport(BaseModel):
    """Transparency report tracking evaluation uncertainty, conflicting signals, and calibration limits."""
    is_uncertain: bool = Field(description="True if confidence is low, input is ambiguous, or contradictory signals exist")
    uncertainty_level: str = Field(description="Categorical uncertainty rating: 'low', 'medium', or 'high'")
    reasons: List[str] = Field(default_factory=list, description="Specific factors contributing to analysis uncertainty")
    calibration_disclosure: str = Field(
        default="Threat scores are deterministic rule-and-model composites. Raw ML probabilities from Model A and Model B are uncalibrated estimates.",
        description="Explicit disclosure regarding probability calibration"
    )
    conflicting_signals: List[str] = Field(
        default_factory=list,
        description="Contradictory signals identified (e.g. benign text with high-risk URL, or spam text with legitimate domain)"
    )


class UnifiedScanRequest(BaseModel):
    """Request payload for unified multi-vector scan."""
    text: Optional[str] = Field(default=None, max_length=20000, description="Message, email, or chat body text to analyze")
    urls: Optional[List[str]] = Field(default=None, description="Optional list of specific URLs to analyze")
    include_explanation: bool = Field(default=True, description="Whether to include structured threat explanation")


class UnifiedReportResponse(BaseModel):
    """Comprehensive Phase 4 Unified Evidence Fusion & Threat Report."""
    case_id: str = Field(description="Unique investigation case tracking identifier")
    verdict: str = Field(description="Deterministic threat verdict: 'benign', 'suspicious', 'high-risk', or 'inconclusive'")
    score: float = Field(description="Deterministic composite threat risk score (0.0 to 100.0)")
    evidence_by_modality: Dict[str, List[NormalizedEvidence]] = Field(
        default_factory=dict,
        description="Evidence partitioned by source modality ('text', 'url', 'screenshot', 'audio')"
    )
    all_evidence: List[NormalizedEvidence] = Field(
        default_factory=list,
        description="Deduplicated master evidence register"
    )
    manipulation_tactics: List[ManipulationTactic] = Field(
        default_factory=list,
        description="Social engineering and manipulation tactics backed by excerpts"
    )
    supporting_excerpts: List[str] = Field(
        default_factory=list,
        description="Distinct supporting text excerpts that triggered indicators"
    )
    model_signals: Dict[str, Any] = Field(
        default_factory=dict,
        description="Signals from Model A (SMS text classifier) and Model B (PhiUSIIL URL classifier)"
    )
    missing_checks: List[str] = Field(
        default_factory=list,
        description="Explicit enumeration of missing or intentionally omitted security checks"
    )
    uncertainty: UncertaintyReport = Field(
        description="Evaluation uncertainty and conflicting signal metrics"
    )
    safe_next_steps: List[str] = Field(
        default_factory=list,
        description="Prescriptive, actionable safety guidance"
    )
    explanation: StructuredExplanation = Field(
        description="Evidence-grounded structured explanation"
    )
